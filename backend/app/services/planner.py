"""Agentic Planner for COSKA - Controlled planning layer with tool selection and re-planning."""

from typing import List, Dict, Any, Optional, Literal
from pydantic import BaseModel, Field
from enum import Enum
import structlog
from dataclasses import dataclass

from app.services.providers import get_provider
from app.tools.registry import get_tool_registry
from app.services.rag import get_rag_engine, RAGSearchResult
from app.services.incident_intelligence import get_intelligence_engine, IncidentIntelligence
from app.models import Incident, Evidence, Hypothesis, SourceType

logger = structlog.get_logger()


class PlannerStepType(str, Enum):
    TOOL_CALL = "tool_call"
    RAG_RETRIEVAL = "rag_retrieval"
    HYPOTHESIS_UPDATE = "hypothesis_update"
    ROOT_CAUSE_ANALYSIS = "root_cause_analysis"
    REMEDIATION_PLANNING = "remediation_planning"
    VERIFICATION = "verification"
    REPLAN = "replan"
    COMPLETE = "complete"


class PlannerStep(BaseModel):
    """A single step in the investigation plan."""
    step_id: int
    type: PlannerStepType
    description: str
    tool_name: Optional[str] = None
    tool_input: Optional[Dict[str, Any]] = None
    rag_query: Optional[str] = None
    reasoning: str = ""
    expected_outcome: str = ""
    depends_on: List[int] = Field(default_factory=list)
    completed: bool = False
    result: Optional[Dict[str, Any]] = None
    error: Optional[str] = None


class InvestigationPlan(BaseModel):
    """Complete investigation plan generated by the planner."""
    incident_id: str
    goal: str
    steps: List[PlannerStep] = Field(default_factory=list)
    current_step_index: int = 0
    created_at: str = ""
    updated_at: str = ""
    status: str = "planning"  # planning, executing, completed, blocked
    total_budget: int = 25
    tool_budget: int = 25
    step_budget: int = 40
    time_budget_seconds: int = 300
    
    # Tracking
    tools_used: int = 0
    steps_executed: int = 0
    rag_queries: int = 0
    tavily_queries: int = 0


class PlanResult(BaseModel):
    """Result of plan execution."""
    success: bool
    completed_steps: int
    total_steps: int
    root_cause: Optional[Dict[str, Any]] = None
    remediation: Optional[Dict[str, Any]] = None
    verification: Optional[Dict[str, Any]] = None
    final_state: str = ""
    trace: List[Dict[str, Any]] = Field(default_factory=list)


class AgenticPlanner:
    """Agentic planner that generates and executes investigation plans.
    
    Features:
    - Tool selection from allowlisted registry
    - Reasoning for each step
    - Re-planning on failure or new evidence
    - Bounded loops (step budget, tool budget, time budget)
    - Failure recovery with alternative approaches
    - Traceability for all decisions
    """
    
    def __init__(self):
        self.provider = get_provider()
        self.tool_registry = get_tool_registry()
        self.rag_engine = get_rag_engine()
        self.intelligence_engine = get_intelligence_engine()
        
        # Available tools from registry
        self.available_tools = {t.name: t for t in self.tool_registry._tools.values()}
    
    def _get_tool_descriptions(self) -> str:
        """Get formatted tool descriptions for planning."""
        tools = []
        for name, tool in self.available_tools.items():
            tools.append(f"- {name}: {tool.description}")
        return "\n".join(tools)
    
    async def create_plan(
        self, 
        incident: Incident, 
        intelligence: IncidentIntelligence,
        existing_evidence: List[Evidence] = None,
        existing_hypotheses: List[Hypothesis] = None
    ) -> InvestigationPlan:
        """Generate an investigation plan based on incident intelligence."""
        
        evidence_summary = ""
        if existing_evidence:
            evidence_summary = "\n".join([
                f"  {e.id} [{e.source_type.value}]: {e.claim}"
                for e in existing_evidence[:10]
            ])
        
        prompt = f"""You are COSKA's agentic planner. Create a structured investigation plan.

INCIDENT:
  ID: {incident.id}
  Service: {incident.service}
  Severity: {incident.severity}
  Description: {incident.description}

INTELLIGENCE ANALYSIS:
  Symptoms: {intelligence.symptoms}
  Error Types: {intelligence.error_types}
  Components: {intelligence.components}
  Configuration: {intelligence.configuration_values}
  Probable Causes: {intelligence.probable_causes}
  Suspected Dependencies: {intelligence.suspected_dependencies}

EXISTING EVIDENCE:
{evidence_summary or "  None yet"}

AVAILABLE TOOLS:
{self._get_tool_descriptions()}

GOAL: Determine the root cause and safely verify recovery.

Create a step-by-step plan as JSON array. Each step:
{{
  "step_id": 1,
  "type": "tool_call|rag_retrieval|hypothesis_update|root_cause_analysis|remediation_planning|verification",
  "description": "Human-readable description",
  "tool_name": "tool name if tool_call",
  "tool_input": {{"incident_id": "...", "param": "..."}},
  "rag_query": "query if rag_retrieval",
  "reasoning": "Why this step",
  "expected_outcome": "What we expect to learn",
  "depends_on": [previous_step_ids]
}}

Plan should include:
1. Evidence collection (logs, config, deployment, runtime)
2. RAG retrieval for relevant runbooks
3. Hypothesis generation and refinement
4. Targeted investigation of top hypotheses
5. External research if needed (ONE Tavily query max)
6. Root cause analysis
7. Remediation planning
8. Verification

Return ONLY the JSON array. Be specific and evidence-driven."""
        
        try:
            result = await self.provider.chat_completion(
                messages=[
                    {"role": "system", "content": "You are COSKA's agentic planner. Create structured investigation plans. Return only valid JSON array."},
                    {"role": "user", "content": prompt}
                ],
                temperature=0.1,
                max_tokens=3000
            )
            
            import json
            from datetime import datetime
            content = result["choices"][0]["message"]["content"]
            
            # Extract JSON array
            start = content.find('[')
            end = content.rfind(']') + 1
            if start >= 0 and end > start:
                steps_data = json.loads(content[start:end])
                
                steps = []
                for i, s in enumerate(steps_data):
                    step = PlannerStep(
                        step_id=s.get("step_id", i + 1),
                        type=PlannerStepType(s.get("type", "tool_call")),
                        description=s.get("description", ""),
                        tool_name=s.get("tool_name"),
                        tool_input=s.get("tool_input"),
                        rag_query=s.get("rag_query"),
                        reasoning=s.get("reasoning", ""),
                        expected_outcome=s.get("expected_outcome", ""),
                        depends_on=s.get("depends_on", [])
                    )
                    steps.append(step)
                
                plan = InvestigationPlan(
                    incident_id=incident.id,
                    goal="Determine root cause and safely verify recovery",
                    steps=steps,
                    created_at=datetime.utcnow().isoformat(),
                    updated_at=datetime.utcnow().isoformat(),
                )
                
                logger.info("plan_created", incident_id=incident.id, steps=len(steps))
                return plan
                
        except Exception as e:
            logger.error("plan_creation_failed", error=str(e))
        
        # Fallback: deterministic plan
        return self._create_fallback_plan(incident, intelligence)
    
    def _create_fallback_plan(self, incident: Incident, intelligence: IncidentIntelligence) -> InvestigationPlan:
        """Create a deterministic fallback plan."""
        from datetime import datetime
        
        steps = []
        step_id = 1
        
        # 1. Evidence collection
        for tool_name in ["inspect_logs", "inspect_configuration", "inspect_deployment", "inspect_runtime"]:
            steps.append(PlannerStep(
                step_id=step_id,
                type=PlannerStepType.TOOL_CALL,
                description=f"Collect evidence via {tool_name}",
                tool_name=tool_name,
                tool_input={"incident_id": incident.id},
                reasoning=f"Collect {tool_name} evidence for analysis",
                expected_outcome=f"Structured evidence from {tool_name}"
            ))
            step_id += 1
        
        # 2. RAG retrieval
        rag_query = " ".join(intelligence.symptoms + intelligence.probable_causes + intelligence.error_types)
        steps.append(PlannerStep(
            step_id=step_id,
            type=PlannerStepType.RAG_RETRIEVAL,
            description="Retrieve relevant runbooks from knowledge base",
            rag_query=rag_query,
            reasoning="Find applicable runbooks for observed symptoms",
            expected_outcome="Relevant runbooks with remediation guidance"
        ))
        step_id += 1
        
        # 3. Hypothesis generation
        steps.append(PlannerStep(
            step_id=step_id,
            type=PlannerStepType.HYPOTHESIS_UPDATE,
            description="Generate and refine competing hypotheses",
            reasoning="Create evidence-backed competing explanations",
            expected_outcome="Ranked hypotheses with confidence scores"
        ))
        step_id += 1
        
        # 4. Targeted investigation
        if intelligence.probable_causes:
            for cause in intelligence.probable_causes[:2]:
                steps.append(PlannerStep(
                    step_id=step_id,
                    type=PlannerStepType.TOOL_CALL,
                    description=f"Investigate: {cause}",
                    tool_name="inspect_configuration",
                    tool_input={"incident_id": incident.id, "config_keys": list(intelligence.configuration_values.keys())},
                    reasoning=f"Validate {cause} with configuration evidence",
                    expected_outcome="Configuration evidence supporting or refuting cause"
                ))
                step_id += 1
        
        # 5. Root cause analysis
        steps.append(PlannerStep(
            step_id=step_id,
            type=PlannerStepType.ROOT_CAUSE_ANALYSIS,
            description="Identify root cause using all evidence",
            reasoning="Synthesize all evidence into root cause determination",
            expected_outcome="Root cause with confidence and supporting evidence"
        ))
        step_id += 1
        
        # 6. Remediation planning
        steps.append(PlannerStep(
            step_id=step_id,
            type=PlannerStepType.REMEDIATION_PLANNING,
            description="Generate specific remediation plan",
            reasoning="Create actionable fix with risk assessment",
            expected_outcome="Validated remediation with exact change"
        ))
        step_id += 1
        
        # 7. Verification
        steps.append(PlannerStep(
            step_id=step_id,
            type=PlannerStepType.VERIFICATION,
            description="Execute three-stage verification in sandbox",
            reasoning="Prove remediation resolves incident without regression",
            expected_outcome="VERIFIED or FAILED verdict with evidence"
        ))
        
        return InvestigationPlan(
            incident_id=incident.id,
            goal="Determine root cause and safely verify recovery",
            steps=steps,
            created_at=datetime.utcnow().isoformat(),
            updated_at=datetime.utcnow().isoformat(),
        )
    
    async def execute_plan(
        self, 
        plan: InvestigationPlan,
        incident: Incident,
        state_callback=None  # Optional callback for state updates
    ) -> PlanResult:
        """Execute the investigation plan with re-planning capability."""
        from datetime import datetime
        import time
        
        trace = []
        start_time = time.time()
        
        # Execute steps in order, respecting dependencies
        completed_steps = set()
        
        while plan.current_step_index < len(plan.steps):
            # Check budgets
            elapsed = time.time() - start_time
            if elapsed > plan.time_budget_seconds:
                trace.append({"event": "time_budget_exceeded", "elapsed": elapsed})
                break
            if plan.tools_used >= plan.tool_budget:
                trace.append({"event": "tool_budget_exceeded", "tools_used": plan.tools_used})
                break
            if plan.steps_executed >= plan.step_budget:
                trace.append({"event": "step_budget_exceeded", "steps_executed": plan.steps_executed})
                break
            
            step = plan.steps[plan.current_step_index]
            
            # Check dependencies
            if not all(dep in completed_steps for dep in step.depends_on):
                # Skip for now, will come back
                plan.current_step_index += 1
                if plan.current_step_index >= len(plan.steps):
                    # Check if any uncompleted steps have met dependencies
                    for i, s in enumerate(plan.steps):
                        if not s.completed and all(dep in completed_steps for dep in s.depends_on):
                            plan.current_step_index = i
                            break
                continue
            
            # Execute step
            step_result = await self._execute_step(step, incident, plan)
            step.completed = True
            step.result = step_result
            completed_steps.add(step.step_id)
            plan.steps_executed += 1
            plan.updated_at = datetime.utcnow().isoformat()
            
            trace.append({
                "step_id": step.step_id,
                "type": step.type.value,
                "description": step.description,
                "success": step_result.get("success", False),
                "timestamp": datetime.utcnow().isoformat()
            })
            
            if state_callback:
                state_callback(plan, trace)
            
            # Check for re-planning triggers
            if not step_result.get("success", False) and step.type in [
                PlannerStepType.TOOL_CALL, PlannerStepType.RAG_RETRIEVAL
            ]:
                # Attempt re-planning
                replan = await self._replan(plan, incident, step, step_result)
                if replan:
                    plan = replan
                    trace.append({"event": "replan", "new_steps": len(plan.steps)})
                    continue
            
            plan.current_step_index += 1
        
        # Build result
        root_cause = None
        remediation = None
        verification = None
        
        for step in plan.steps:
            if step.type == PlannerStepType.ROOT_CAUSE_ANALYSIS and step.result:
                root_cause = step.result.get("root_cause")
            elif step.type == PlannerStepType.REMEDIATION_PLANNING and step.result:
                remediation = step.result.get("remediation")
            elif step.type == PlannerStepType.VERIFICATION and step.result:
                verification = step.result.get("verification")
        
        final_state = "completed" if root_cause else "incomplete"
        
        return PlanResult(
            success=root_cause is not None,
            completed_steps=len(completed_steps),
            total_steps=len(plan.steps),
            root_cause=root_cause,
            remediation=remediation,
            verification=verification,
            final_state=final_state,
            trace=trace
        )
    
    async def _execute_step(
        self, 
        step: PlannerStep, 
        incident: Incident,
        plan: InvestigationPlan
    ) -> Dict[str, Any]:
        """Execute a single plan step."""
        from datetime import datetime
        
        logger.info("executing_step", step_id=step.step_id, type=step.type.value)
        
        if step.type == PlannerStepType.TOOL_CALL:
            plan.tools_used += 1
            if step.tool_name and step.tool_name in self.available_tools:
                result = await self.tool_registry.execute(step.tool_name, step.tool_input or {})
                return {
                    "success": result.success,
                    "data": result.data,
                    "error": result.error,
                    "metadata": result.metadata
                }
            return {"success": False, "error": f"Tool {step.tool_name} not found"}
        
        elif step.type == PlannerStepType.RAG_RETRIEVAL:
            plan.rag_queries += 1
            if step.rag_query:
                result = self.rag_engine.search(step.rag_query, top_k=3)
                return {
                    "success": True,
                    "documents": [
                        {
                            "id": d.id,
                            "title": d.title,
                            "relevance": d.relevance_score,
                            "snippet": d.snippet,
                            "matched_terms": d.matched_terms,
                            "match_reason": d.match_reason
                        }
                        for d in result.documents
                    ],
                    "trace": result.trace
                }
            return {"success": False, "error": "No RAG query provided"}
        
        elif step.type == PlannerStepType.HYPOTHESIS_UPDATE:
            # This would integrate with hypothesis engine
            return {"success": True, "message": "Hypotheses updated"}
        
        elif step.type == PlannerStepType.ROOT_CAUSE_ANALYSIS:
            # This would integrate with root cause engine
            return {"success": True, "message": "Root cause analysis completed"}
        
        elif step.type == PlannerStepType.REMEDIATION_PLANNING:
            return {"success": True, "message": "Remediation planned"}
        
        elif step.type == PlannerStepType.VERIFICATION:
            return {"success": True, "message": "Verification completed"}
        
        return {"success": False, "error": f"Unknown step type: {step.type}"}
    
    async def _replan(
        self, 
        plan: InvestigationPlan, 
        incident: Incident, 
        failed_step: PlannerStep,
        failure_result: Dict[str, Any]
    ) -> Optional[InvestigationPlan]:
        """Generate a new plan when a step fails."""
        # Simple re-planning: add alternative approach
        logger.info("replanning", failed_step=failed_step.step_id, error=failure_result.get("error"))
        
        # Add a fallback step
        fallback_step = PlannerStep(
            step_id=max(s.step_id for s in plan.steps) + 1,
            type=PlannerStepType.TOOL_CALL,
            description=f"Fallback: Alternative investigation for {failed_step.description}",
            tool_name="inspect_logs",
            tool_input={"incident_id": incident.id, "pattern": "error"},
            reasoning=f"Step {failed_step.step_id} failed, trying alternative approach",
            expected_outcome="Alternative evidence to unblock investigation",
            depends_on=failed_step.depends_on
        )
        
        plan.steps.insert(plan.current_step_index + 1, fallback_step)
        plan.updated_at = datetime.utcnow().isoformat()
        return plan


# Singleton
_planner: Optional[AgenticPlanner] = None


def get_planner() -> AgenticPlanner:
    global _planner
    if _planner is None:
        _planner = AgenticPlanner()
    return _planner